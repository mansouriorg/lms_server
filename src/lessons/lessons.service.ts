// src/lessons/lessons.service.ts
import { Injectable, NotFoundException, ConflictException } from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';
import { CreateLessonDto } from './dto/create-lesson.dto';
import { UpdateLessonDto } from './dto/update-lesson.dto';

@Injectable()
export class LessonsService {
  constructor(private readonly prisma: PrismaService) {}

  // --- ADMIN METHODS (Managing the Curriculum) ---

  async create(dto: CreateLessonDto) {
    // Verify the Bootcamp (Stage) actually exists
    const stage = await this.prisma.stage.findUnique({ where: { id: dto.stageId } });
    if (!stage) {
      throw new NotFoundException('Le bootcamp (Stage) est introuvable.');
    }

    const lesson = await this.prisma.lesson.create({ data: dto });
    return { message: 'Leçon créée avec succès.', lesson };
  }

  async update(id: string, dto: UpdateLessonDto) {
    const lesson = await this.prisma.lesson.findUnique({ where: { id } });
    if (!lesson) throw new NotFoundException('Leçon introuvable.');

    const updatedLesson = await this.prisma.lesson.update({
      where: { id },
      data: dto,
    });
    return { message: 'Leçon mise à jour.', lesson: updatedLesson };
  }

  async remove(id: string) {
    const lesson = await this.prisma.lesson.findUnique({ where: { id } });
    if (!lesson) throw new NotFoundException('Leçon introuvable.');

    await this.prisma.lesson.delete({ where: { id } });
    return { message: 'Leçon supprimée avec succès.' };
  }

  // --- STUDENT METHODS (Learning & Progress) ---

  // Fetch all lessons for a specific bootcamp, ordered correctly
  async findAllByStage(stageId: string) {
    return this.prisma.lesson.findMany({
      where: { stageId },
      orderBy: { order: 'asc' }, // Crucial: Ensures Lesson 1 comes before Lesson 2
    });
  }

  // The core e-learning feature: Tracking progress
  async markAsCompleted(userId: string, lessonId: string) {
    // 1. Check if the lesson exists
    const lesson = await this.prisma.lesson.findUnique({ where: { id: lessonId } });
    if (!lesson) throw new NotFoundException('Leçon introuvable.');

    // 2. Check if the student already completed this lesson
    // We use the compound unique ID generated by Prisma
    const existingProgress = await this.prisma.progress.findUnique({
      where: {
        userId_lessonId: {
          userId: userId,
          lessonId: lessonId,
        },
      },
    });

    if (existingProgress) {
      throw new ConflictException('Vous avez déjà terminé cette leçon.');
    }

    // 3. Record the progress
    const progress = await this.prisma.progress.create({
      data: {
        userId: userId,
        lessonId: lessonId,
        completed: true,
      },
    });

    return { 
      message: 'Félicitations ! Leçon terminée.', 
      progress 
    };
  }

  // --- NEW: Calculate Overall Course Progress ---
  async getStageProgress(userId: string, stageId: string) {
    // 1. Count the total number of lessons in this specific bootcamp
    const totalLessons = await this.prisma.lesson.count({
      where: { stageId: stageId },
    });

    // If the admin hasn't added any lessons yet, the progress is naturally 0%
    if (totalLessons === 0) {
      return {
        total: 0,
        completed: 0,
        percentage: 0,
        message: "Ce cours n'a pas encore de leçons.",
      };
    }

    // 2. Count how many lessons THIS specific user has completed in THIS specific bootcamp
    const completedLessons = await this.prisma.progress.count({
      where: {
        userId: userId,
        lesson: {
          stageId: stageId, // Prisma elegantly filters through the relation!
        },
      },
    });

    // 3. Calculate the percentage and round it to a clean whole number (e.g., 67%)
    const percentage = Math.round((completedLessons / totalLessons) * 100);

    return {
      total: totalLessons,
      completed: completedLessons,
      percentage: percentage,
      message: `Vous avez terminé ${percentage}% de ce cours.`,
    };
  }
}